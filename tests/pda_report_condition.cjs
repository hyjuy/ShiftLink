const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync('shiftlink/mes/web/pda.js','utf8');
const context=vm.createContext({module:{exports:{}}});
context.requestAnimationFrame=()=>{};
vm.runInContext(source,context);
const handlers={};
const fields=new Map();
const section={querySelector:selector=>{
  if(!fields.has(selector))fields.set(selector,{value:'',textContent:''});
  return fields.get(selector);
}};
context.document={getElementById:()=>({addEventListener:(name,handler)=>handlers[name]=handler})};
vm.runInContext('saveReportDraft=()=>{};S.equipment=[{equipment_id:"EQ-1",signals:[{signal:"pressure",unit:"bar"},{signal:"temperature",unit:"degC"}]}];S.reportRecords=[{type:"고장·정비",equipment:["EQ-1"],causes:[]}];S.snapshot=null;',context);
context.Option=class {constructor(text,value){this.text=text;this.value=value;}};
vm.runInContext(source.slice(source.indexOf("$('reportRecords').addEventListener('focusin'"),source.indexOf("$('reportRecords').addEventListener('click'")),context);
const record=()=>JSON.parse(vm.runInContext('JSON.stringify(S.reportRecords[0])',context));
assert.equal(vm.runInContext('reportConditionFields(S.reportRecords[0],0,String)',context),'','new work logs do not ask workers to define sensor thresholds');
const legacy=vm.runInContext('reportConditionFields({condition_signal:"pressure",condition_op:"<",condition_value:"145",condition_unit:"bar"},0,value=>String(value).replaceAll("<","&lt;"))',context);
assert.match(legacy,/pressure &lt; 145 bar/);assert.doesNotMatch(legacy,/<input|<select/,'legacy rules remain readable without a threshold editor');
const causeFields=vm.runInContext('reportCauseFields(S.reportRecords[0],0,()=>"cause-note",String)',context);
assert.match(causeFields,/원인·판단 근거/);assert.match(causeFields,/remove-cause/);assert.equal(record().causes.length,0,'rendering an empty cause must not invent evidence');
handlers.input({target:{dataset:{record:'0',cause:'0',key:'note'},type:'textarea',value:'필터 오염 확인',closest:()=>section}});
assert.equal(record().causes[0].note,'필터 오염 확인','first cause is editable without adding a row');
handlers.input({target:{dataset:{record:'0',key:'operating_context'},type:'textarea',value:'기동 직후에만 소음 발생',closest:()=>section}});
assert.equal(record().operating_context,'기동 직후에만 소음 발생');
vm.runInContext('S.reportRecords[0].action_steps=[{action:"전원 격리",observed_result:"정지 확인",failed:false}];',context);
const safety={dataset:{record:'0'},value:'',classList:{contains:name=>name==='report-safety-source'},closest:()=>section,
  replaceChildren(...options){this.options=options;},append(option){this.options.push(option);}};
handlers.focusin({target:safety});
assert.equal(safety.options[1].text,'1. 전원 격리');
safety.value='0';handlers.change({target:safety});
assert.equal(record().safety_action,'전원 격리');
assert.equal(record().safety_notes,undefined,'selecting an action does not invent a risk or a safety basis');
assert.equal(record().safety_basis,undefined);
vm.runInContext('S.reportRecords[0].action_steps[0].action="잔압 확인";',context);
handlers.focusin({target:safety});
assert.equal(safety.options[1].text,'1. 잔압 확인','options reflect the latest action text');
context.window={confirm:()=>false};
handlers.change({target:safety});assert.equal(record().safety_action,'전원 격리','declining replacement keeps the existing text');
context.window.confirm=()=>true;
handlers.change({target:safety});assert.equal(record().safety_action,'잔압 확인');
console.log('PASS: plain operating context, inline cause evidence, preserved legacy conditions, explicit safety reuse');
