"""Build a local, synthetic 69-signal fault dataset.

Example: python scripts/build_mes_fault_dataset.py --out output/mes-fault-dataset --runs-per-split 4 --ticks 300 --seed 31
The feature and private label files join on (run_id, sequence). Only the feature
file may be shared; labels and manifest reveal the synthetic injection schedule.
These files are not real-equipment validation evidence.
"""
import argparse
import json
import math
import sys
from collections import Counter
from dataclasses import replace
from datetime import datetime, timedelta, timezone
from hashlib import sha256
from pathlib import Path
from random import Random

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from shiftlink.mes.configuration import from_catalog
from shiftlink.mes.contracts import Run
from shiftlink.mes.random_factory import RandomFactoryEngine
from shiftlink.mes.scenarios.priority import expand


CATALOG = ROOT / "docs/data/reference/00_plant_and_relations.json"
SPLITS = ("train", "validation", "test")
GENERATOR_VERSION = 7

# These mechanisms are deliberately defined without importing the symptom
# patterns used by the MES detector. They perturb a physical response over time
# instead of assigning the detector's expected low/normal/high state vector.
CHALLENGE_MECHANISMS = {
    "HPU": (("hydraulic_leak", (("hpu_pressure", -1, 1.2, 0),
                                ("hpu_pump_outlet_pressure", -1, 1.0, 1),
                                ("hpu_accumulator_fluid_pressure", -1, .8, 3),
                                ("hpu_flow", -1, .9, 2),
                                ("hpu_pump_current", 1, .45, 1))),
            ("heat_rejection_loss", (("hpu_oil_temp", 1, 1.1, 0),
                                     ("hpu_cooler_oil_out_temp", 1, .7, 3)))),
    "PDP": (("bus_sag", (("bus_voltage", -1, 1.1, 0), ("bus_current", 1, .35, 2))),),
    "CAU": (("air_leak", (("air_pressure", -1, 1.1, 0), ("air_flow", 1, .8, 2),
                         ("compressor_current", 1, .55, 3))),),
    "GR": (("bearing_drag", (("gr_rpm", -1, .9, 0), ("gr_current", 1, 1.0, 1),
                             ("gr_vib_rms", 1, .9, 2), ("gr_brg_temp", 1, .6, 4))),),
    "RT": (("roller_drag", (("rt_speed", -1, .9, 0), ("rt_motor_current", 1, 1.0, 1),
                            ("rt_vib_rms", 1, .8, 2))),),
    "CV": (("belt_drag", (("cv_speed", -1, 1.0, 0), ("cv_motor_current", 1, .9, 1))),
           ("belt_slack", (("cv_speed", -1, .9, 0), ("cv_belt_tension", -1, .8, 2)))),
}

# Only responses with a defensible signal path are modeled. The relation graph
# supplies the affected equipment and delay; the mechanism supplies direction.
# A downstream response is weaker than the initiating fault and is not a new
# fault label. Other graph edges have no invented sensor response.
RELATION_RESPONSES = {
    ("hydraulic_leak", "hydraulic_supply"): (("rt_clamp_press", -1, .35),),
    ("bus_sag", "power_supply"): (("gr_rpm", -1, .30),),
    ("bearing_drag", "drive"): (("rt_speed", -1, .30), ("cv_speed", -1, .30)),
}


class IndependentChallenge:
    """Offline fault mechanisms independent of the detector's PATTERNS table."""

    def __init__(self, config, seed, hazard, warmup_ticks=0, response_scale=1.0):
        self.rng = Random(f"independent-mes-challenge:{seed}")
        self.hazard = hazard
        self.warmup_ticks = warmup_ticks
        self.response_scale = response_scale
        self.specs = {(eq.equipment_id, spec.signal): spec for eq in config.equipment for spec in eq.signals}
        self.options = {
            eq.equipment_id: [(name, effects) for name, effects in CHALLENGE_MECHANISMS.get(eq.code.split("-")[0], ())
                              if all((eq.equipment_id, signal) in self.specs for signal, *_ in effects)]
            for eq in config.equipment if eq.active
        }
        # A measurement-channel failure is a separate cause class. Choose only
        # sampled continuous channels: queue occupancy and event/manual values
        # are generated by a different acquisition process.
        self.sensor_options = {
            eq.equipment_id: [spec.signal for spec in eq.signals
                              if spec.semantics.get("acquisition") == "continuous"
                              and spec.unit != "bool" and spec.normal_min is not None
                              and spec.normal_max is not None]
            for eq in config.equipment if eq.active
        }
        self.relations = tuple(config.relations) + tuple(config.branches)
        self.active = []
        self.cooldown = {}
        self.counter = 0

    def step(self, sequence):
        for fault in self.active:
            if sequence >= fault["end"]:
                self.cooldown[fault["equipment_id"]] = sequence + self.rng.randint(8, 20)
        self.active = [fault for fault in self.active if sequence < fault["end"]]
        occupied = {fault["equipment_id"] for fault in self.active}
        choices = [eq for eq, options in self.options.items()
                   if options and eq not in occupied and sequence >= self.cooldown.get(eq, 0)]
        self.rng.shuffle(choices)
        for eq in choices:
            if len(self.active) >= 2:
                break
            if sequence <= self.warmup_ticks or self.rng.random() >= self.hazard:
                continue
            if self.sensor_options[eq] and self.rng.random() < .2:
                signal = self.rng.choice(self.sensor_options[eq])
                name, effects, kind = f"sensor_bias:{signal}", ((signal, self.rng.choice((-1, 1)), 1.0, 0),), "sensor"
            else:
                name, effects = self.rng.choice(self.options[eq])
                kind = "equipment"
            self.counter += 1
            self.active.append({"id": f"challenge-{self.counter:06d}", "equipment_id": eq,
                                "pattern_id": name, "kind": kind, "start": sequence,
                                "end": sequence + self.rng.randint(14, 36),
                                "mode": self.rng.choice(("abrupt", "ramp", "intermittent")),
                                "severity": self.rng.uniform(.45, 1.0), "effects": effects})
        result = []
        for fault in self.active:
            age = sequence - fault["start"]
            attack = min(1.0, (age + 1) / 7) if fault["mode"] == "ramp" else 1.0
            release = min(1.0, (fault["end"] - sequence) / 4)
            pulse = 0.0 if fault["mode"] == "intermittent" and age % 6 in (3, 4) else 1.0
            result.append({key: value for key, value in fault.items() if key != "effects"} |
                          {"intensity": round(attack * release * pulse, 6)})
        return result

    def overlay(self, measurements, faults, sequence):
        changed = {(m.equipment_id, m.signal): m for m in measurements}
        for fault in faults:
            original = next(item for item in self.active if item["id"] == fault["id"])
            age = sequence - fault["start"]
            for signal, direction, gain, lag in original["effects"]:
                # Equipment transport speed is produced by the motion engine;
                # only an isolated speed-sensor bias may corrupt its reading.
                if fault.get("kind") == "equipment" and signal in {"rt_speed", "cv_speed"}:
                    continue
                key = (fault["equipment_id"], signal)
                measurement, spec = changed[key], self.specs[key]
                if measurement.quality != "good" or age < lag or spec.normal_min is None or spec.normal_max is None:
                    continue
                span = max(spec.normal_max - spec.normal_min, abs(spec.normal_max) * .1, .001)
                boundary = spec.normal_min if direction < 0 else spec.normal_max
                full_target = boundary + direction * span * fault["severity"] * gain
                target = measurement.value + self.response_scale * (full_target - measurement.value)
                strength = fault["intensity"] * min(1.0, (age - lag + 1) / 5)
                value = measurement.value + strength * (target - measurement.value)
                if spec.unit == "pct":
                    value = max(0, min(100, value))
                elif value < 0:
                    value = 0
                changed[key] = replace(measurement, value=round(value, 6))
            if fault.get("kind") == "sensor":
                continue
            # The cooler-oil flow is a physical branch of the HPU flow, so a
            # source flow loss must be visible there too. It is not a second
            # independent random symptom. A faulty flow sensor must not change
            # this branch, hence the equipment-only guard above.
            if fault["pattern_id"] == "hydraulic_leak":
                source = (fault["equipment_id"], "hpu_flow")
                branch = (fault["equipment_id"], "hpu_cooler_oil_flow")
                if source in changed and branch in changed and changed[branch].quality == "good":
                    changed[branch] = replace(changed[branch], value=changed[source].value)
            elif fault["pattern_id"] == "heat_rejection_loss":
                source = (fault["equipment_id"], "hpu_oil_temp")
                inlet = (fault["equipment_id"], "hpu_cooler_oil_in_temp")
                if source in changed and inlet in changed and changed[inlet].quality == "good":
                    changed[inlet] = replace(changed[inlet], value=changed[source].value)
            for relation in self.relations:
                if relation.from_id != fault["equipment_id"]:
                    continue
                responses = RELATION_RESPONSES.get((fault["pattern_id"], relation.relation_type), ())
                # MES frames advance in seconds. Even a zero-lag utility link
                # cannot show a downstream measurement before the source onset.
                delay = max(1, math.ceil(relation.lag_seconds or 0))
                if age < delay:
                    continue
                strength = fault["intensity"] * min(1.0, (age - delay + 1) / 5)
                for signal, direction, gain in responses:
                    if signal in {"rt_speed", "cv_speed"}:
                        continue
                    key = (relation.to_id, signal)
                    if key not in changed or key not in self.specs:
                        continue
                    measurement, spec = changed[key], self.specs[key]
                    if measurement.quality != "good" or spec.normal_min is None or spec.normal_max is None:
                        continue
                    # Move a measured response by a fraction of its own normal
                    # span; unlike the source effect it need not cross a limit.
                    span = spec.normal_max - spec.normal_min
                    value = measurement.value + direction * span * gain * fault["severity"] * strength * self.response_scale
                    if spec.unit == "pct":
                        value = min(100, max(0, value))
                    else:
                        value = max(0, value)
                    changed[key] = replace(measurement, value=round(value, 6))
        return tuple(changed[(m.equipment_id, m.signal)] for m in measurements)


class IndependentFactoryEngine(RandomFactoryEngine):
    """Feed latent transport faults into coil motion before each simulator tick."""

    def __init__(self, *args, **kwargs):
        self.transport_factors = {}
        self._motion_speed = {}
        self._record_motion_speed = False
        self.response_scale = kwargs.pop("response_scale", 1.0)
        super().__init__(*args, **kwargs)

    def set_faults(self, faults):
        factors = {}
        for fault in faults:
            if fault.get("kind") != "equipment" or fault["intensity"] <= 0:
                continue
            if fault["pattern_id"] in {"roller_drag", "belt_drag", "belt_slack"}:
                equipment_id = fault["equipment_id"]
                factors[equipment_id] = min(factors.get(equipment_id, 1.0),
                                            max(.2, 1 - .6 * self.response_scale * fault["severity"] * fault["intensity"]))
            if fault["pattern_id"] == "bearing_drag":
                age = self.snapshot.sequence + 1 - fault.get("start", self.snapshot.sequence + 1)
                for relation in tuple(self.config.relations) + tuple(self.config.branches):
                    if relation.from_id != fault["equipment_id"] or relation.relation_type != "drive":
                        continue
                    if age < max(1, math.ceil(relation.lag_seconds or 0)):
                        continue
                    equipment_id = relation.to_id
                    factors[equipment_id] = min(factors.get(equipment_id, 1.0),
                                                max(.2, 1 - .3 * self.response_scale * fault["severity"] * fault["intensity"]))
        self.transport_factors = factors

    def tick(self, count=1):
        if not isinstance(count, int) or isinstance(count, bool) or count < 0:
            raise ValueError("count must be a nonnegative integer")
        if count != 1:
            snapshot = self.snapshot
            for _ in range(count):
                snapshot = self.tick(1)
            return snapshot
        before = self.snapshot.sequence
        self._motion_speed = {}
        snapshot = super().tick(count)
        if snapshot.sequence == before:
            return snapshot
        equipment = {eq.equipment_id: eq for eq in self.config.equipment}
        speed_specs = {(eq.equipment_id, spec.signal): spec for eq in self.config.equipment
                       for spec in eq.signals if spec.signal in {"rt_speed", "cv_speed"}}
        measurements = tuple(
            replace(m, value=self._motion_speed.get(
                (m.equipment_id, m.signal),
                self._measurement_value(equipment[m.equipment_id], speed_specs[(m.equipment_id, m.signal)])))
            if (m.equipment_id, m.signal) in speed_specs and m.quality == "good" else m
            for m in snapshot.measurements)
        self._snapshot = replace(snapshot, measurements=measurements)
        self._symptom_frames[-1] = self._snapshot
        return self.snapshot

    def _move_coils(self):
        self._record_motion_speed = True
        try:
            return super()._move_coils()
        finally:
            self._record_motion_speed = False

    def _measurement_value(self, equipment, signal_spec):
        value = super()._measurement_value(equipment, signal_spec)
        if signal_spec.signal in {"rt_speed", "cv_speed"}:
            value *= self.transport_factors.get(equipment.equipment_id, 1.0)
            if self._record_motion_speed:
                self._motion_speed[(equipment.equipment_id, signal_spec.signal)] = value
        return value


def validate_measurements(config, measurements):
    expected = Counter((eq.equipment_id, spec.signal, spec.unit)
                       for eq in config.equipment if eq.active for spec in eq.signals)
    if sum(expected.values()) != 69:
        raise ValueError(f"expected 69 configured measurement positions, found {sum(expected.values())}")
    actual = Counter((m.equipment_id, m.signal, m.unit) for m in measurements)
    if sum(actual.values()) != 69:
        raise ValueError(f"expected 69 snapshot measurements, found {sum(actual.values())}")
    if actual != expected:
        raise ValueError("snapshot measurements do not match configured signals per equipment")


def build_dataset(out: Path, *, runs_per_split: int = 2, ticks: int = 120,
                  seed: int = 31, hazard: float = .003, profile: str = "pattern",
                  warmup_ticks: int = 0, response_scale: float = 1.0) -> dict:
    if type(runs_per_split) is not int or runs_per_split < 1 or type(ticks) is not int or ticks < 1:
        raise ValueError("runs_per_split and ticks must be positive integers")
    if isinstance(hazard, bool) or not isinstance(hazard, (int, float)) or not math.isfinite(hazard) or not 0 <= hazard <= 1:
        raise ValueError("hazard must be finite and within 0..1")
    if profile not in {"pattern", "independent"}:
        raise ValueError("profile must be pattern or independent")
    if type(warmup_ticks) is not int or not 0 <= warmup_ticks < ticks:
        raise ValueError("warmup_ticks must be an integer within 0..ticks-1")
    if (isinstance(response_scale, bool) or not isinstance(response_scale, (int, float))
            or not math.isfinite(response_scale) or not 0 < response_scale <= 1):
        raise ValueError("response_scale must be finite and within (0, 1]")
    if profile != "independent" and response_scale != 1:
        raise ValueError("response_scale is only supported for the independent profile")
    config = expand(from_catalog(json.loads(CATALOG.read_text(encoding="utf-8"))))
    signal_count = sum(len(eq.signals) for eq in config.equipment if eq.active)
    if signal_count != 69:
        raise ValueError(f"expected 69 configured measurement positions, found {signal_count}")
    out = Path(out)
    out.mkdir(parents=True, exist_ok=False)
    split_counts = {split: Counter() for split in SPLITS}
    split_episode_patterns = {split: Counter() for split in SPLITS}
    seen_episodes = set()
    patterns = Counter()
    equipment = Counter()
    quality = Counter()
    runs = []
    with (out / "features.jsonl").open("x", encoding="utf-8") as feature_file, \
         (out / "labels.jsonl").open("x", encoding="utf-8") as label_file:
        for index in range(len(SPLITS) * runs_per_split):
            split = SPLITS[index // runs_per_split]
            run_seed = seed + index
            nonce = (f"mes-fault-dataset:{split}:{run_seed}" if profile == "pattern"
                     else f"mes-fault-dataset:{profile}:{split}:{run_seed}")
            run_id = sha256(f"{config.config_id}:{nonce}".encode()).hexdigest()[:32]
            started = datetime(2026, 10, 20, tzinfo=timezone.utc) + timedelta(days=index)
            run = Run(run_id=run_id, seed=run_seed, started_at=started,
                      config_id=config.config_id, split=split)
            engine_type = IndependentFactoryEngine if profile == "independent" else RandomFactoryEngine
            engine = engine_type(run, config, run_nonce=nonce,
                                 faults_enabled=profile == "pattern", hazard=hazard,
                                 **({"response_scale": response_scale} if profile == "independent" else {}))
            challenge = IndependentChallenge(config, f"{run_seed}:{nonce}", hazard,
                                             warmup_ticks, response_scale) if profile == "independent" else None
            engine.start()
            runs.append({"run_id": run_id, "split": split, "seed": run_seed,
                         "run_nonce": nonce, "frames": ticks})
            for _ in range(ticks):
                if challenge is None:
                    engine.scheduler.enabled = engine.snapshot.sequence >= warmup_ticks
                    faults = None
                else:
                    faults = challenge.step(engine.snapshot.sequence + 1)
                    engine.set_faults(faults)
                snapshot = engine.tick()
                label = engine.truth[-1] if challenge is None else {"faults": faults}
                engine.truth.clear()
                if challenge is not None:
                    snapshot = replace(snapshot, measurements=challenge.overlay(
                        snapshot.measurements, label["faults"], snapshot.sequence))
                validate_measurements(config, snapshot.measurements)
                coil_counts = Counter(coil["equipment_id"] for coil in snapshot.coils)
                features = {"run_id": run_id, "sequence": snapshot.sequence, "split": split,
                            "simulated_at": snapshot.simulated_at.isoformat(),
                            "line_mode": snapshot.line_mode,
                            "equipment_operating_states": [
                                {"equipment_id": state.equipment_id,
                                 "operating_state": state.operating_state,
                                 "coil_count": coil_counts[state.equipment_id]}
                                for state in snapshot.equipment],
                            "measurements": [{"equipment_id": m.equipment_id,
                                              "signal": m.signal, "value": m.value,
                                              "unit": m.unit, "quality": m.quality,
                                              "observed_at": m.observed_at.isoformat()}
                                             for m in snapshot.measurements]}
                feature_file.write(json.dumps(features, ensure_ascii=False) + "\n")
                label_file.write(json.dumps({"run_id": run_id, "sequence": snapshot.sequence,
                                             "faults": label["faults"]}, ensure_ascii=False) + "\n")
                count = split_counts[split]
                count["frames"] += 1
                count["readings"] += len(snapshot.measurements)
                count["fault_frames"] += bool(label["faults"])
                count["observable_fault_frames"] += any(fault["intensity"] > 0 for fault in label["faults"])
                count["normal_frames"] += not label["faults"]
                for measurement in snapshot.measurements:
                    quality[measurement.quality] += 1
                for fault in label["faults"]:
                    patterns[fault["pattern_id"]] += 1
                    equipment[fault["equipment_id"]] += 1
                    episode = (run_id, fault["id"])
                    if episode not in seen_episodes:
                        seen_episodes.add(episode)
                        count["fault_episodes"] += 1
                        split_episode_patterns[split][fault["pattern_id"]] += 1
    manifest = {
        "is_synthetic": True, "generator_version": GENERATOR_VERSION,
        "config_id": config.config_id, "hazard": hazard, "profile": profile,
        "warmup_ticks": warmup_ticks, "response_scale": response_scale,
        "signal_count": signal_count, "frames": sum(c["frames"] for c in split_counts.values()),
        "readings": sum(c["readings"] for c in split_counts.values()),
        "splits": {split: {**counts, "fault_episodes": counts["fault_episodes"],
                            "fault_episode_patterns": dict(split_episode_patterns[split])}
                   for split, counts in split_counts.items()},
        "fault_pattern_frames": dict(patterns), "fault_equipment_frames": dict(equipment),
        "quality_readings": dict(quality), "runs": runs,
        "feature_file": "features.jsonl", "private_label_file": "labels.jsonl",
        "manifest_private": True,
        "sharing": "Only features.jsonl may be shared; labels.jsonl and manifest.json are restricted.",
        "model_input": "Only measurements, line_mode, and equipment_operating_states (including coil_count) are predictors. run_id, sequence, split, simulated_at, and observed_at are grouping/index fields. fault_level, wait_reason, alarms, scenario, and injection schedule are excluded.",
        "label_definition": "faults lists active injected episodes; intermittent episodes may have intensity 0",
        "independent_mechanism_note": "Independent profile separates equipment faults (several coupled local sensors, selected delayed downstream responses) from isolated sensor bias (one continuous channel, no propagation). RT/CV transport faults reduce simulated coil progress before the tick, and emitted transport speed follows that motion; a speed-sensor bias may differ from physical motion. Other actuator and operating-state feedback is not modeled. response_scale reduces fault displacement from each clean measurement, not from the catalog midpoint.",
        "mechanism_prior_provenance": "CHALLENGE_MECHANISMS and RELATION_RESPONSES are project-authored qualitative assumptions; they have not been calibrated or approved against plant measurements or an equipment expert review. Downstream links and delays come from config.relations/config.branches.",
        "split_unit": "run; each split has distinct seed and run_nonce",
        "replay_note": "Identical replay is only expected with the same generator and simulator code; code changes may alter output.",
        "warning": "Synthetic injection labels do not establish real equipment diagnosis accuracy.",
    }
    (out / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--runs-per-split", type=int, default=2)
    parser.add_argument("--ticks", type=int, default=120)
    parser.add_argument("--seed", type=int, default=31)
    parser.add_argument("--hazard", type=float, default=.003)
    parser.add_argument("--profile", choices=("pattern", "independent"), default="pattern")
    parser.add_argument("--warmup-ticks", type=int, default=0)
    parser.add_argument("--response-scale", type=float, default=1.0,
                        help="Independent-profile fault response amplitude; 1.0 preserves the baseline")
    args = parser.parse_args()
    manifest = build_dataset(args.out, runs_per_split=args.runs_per_split,
                             ticks=args.ticks, seed=args.seed, hazard=args.hazard, profile=args.profile,
                             warmup_ticks=args.warmup_ticks, response_scale=args.response_scale)
    print(json.dumps({key: manifest[key] for key in ("frames", "readings", "splits")}, ensure_ascii=False))


if __name__ == "__main__":
    main()
