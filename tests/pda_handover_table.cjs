const assert = require('node:assert/strict');
const {handoverTableRow, hasHandoverNotes, handoverEntries, selectedReportPayload} = require('../shiftlink/mes/web/pda.js');
const equipment = [{equipment_id:'EQ-1',code:'HPU-01'}, {equipment_id:'EQ-2',code:'GR-01'}];
const draft = {ids:['EQ-1','EQ-2'],author:'로컬 검증',start:'2026-10-16T16:00',end:'2026-10-17T00:00',memo:'',context:'센서 근거',
  records:[{type:'고장·정비',equipment:['EQ-1'],story:'유압 저하 확인 후 필터 점검',causes:[],result:'다음 조 압력 재확인',pms:null,candidate:false},
    {type:'PMS 정비',equipment:['EQ-2'],story:'구동부 윤활',causes:[],result:'윤활 완료',pms:'PMS-01',candidate:false}]};
const saved = {...selectedReportPayload(draft,equipment),handover_id:'LOCAL-1',created_at:'2026-10-17T01:00:00+09:00'};
const original = JSON.stringify(saved);
const row = handoverTableRow(saved,equipment);
assert.equal(row.date,'2026-10-16','use the work date, not the save date');
assert.equal(row.hours,'16:00 – 00:00 (+1일)');
assert.equal(row.author,'로컬 검증');
assert.equal(row.equipment,'HPU-01 · GR-01');
assert.match(row.summary,/고장·정비 · 유압 저하/);assert.match(row.summary,/PMS 정비 · 구동부 윤활/);
assert.match(row.results,/다음 조 압력 재확인/);assert.match(row.results,/윤활 완료/);
assert.equal(JSON.stringify(saved),original,'rendering must not change the stored report');
const normal = handoverTableRow({...saved,work_report:{records:[],legacy_memo:''},memo_text:'별도 작성 내용 없음'},equipment);
assert.equal(normal.summary,'별도 작성 내용 없음');assert.equal(normal.results,'미기재');
assert.equal(hasHandoverNotes(saved),true);
assert.equal(hasHandoverNotes({...saved,work_report:{records:[],legacy_memo:'',mes_context:'MES 센서값'},memo_text:'별도 작성 내용 없음'}),false,'sensor-only work logs are not handovers');
assert.equal(hasHandoverNotes({...saved,work_report:{records:[],legacy_memo:'다음 근무에서 재확인'}}),true);
assert.equal(hasHandoverNotes({...saved,work_report:{records:[],remarks:'추가 인계 메모'}}),true);
assert.equal(hasHandoverNotes({kind:'work_log',memo_text:'이전 양식 인계 메모'}),true);
assert.equal(hasHandoverNotes({kind:'work_log',memo_text:'별도 작성 내용 없음'}),false);
assert.equal(hasHandoverNotes({kind:'work_log',work_report:{records:[{story:'   '}],legacy_memo:''}}),false);
assert.equal(hasHandoverNotes({open_items:[{text:'GR-01 점검 요청'}]}),true);
const entries = handoverEntries({...saved,work_report:{...saved.work_report,records:saved.work_report.records.map((r,i)=>({...r,occurred_at:i?'2026-10-17T00:10':'2026-10-16T18:20'}))}},equipment);
assert.equal(entries.length,2);assert.equal(entries[0].row.equipment,'HPU-01');assert.equal(entries[1].row.equipment,'GR-01');
assert.equal(entries[0].row.occurred,'2026-10-16\n18:20');assert.equal(entries[1].row.occurred,'2026-10-17\n00:10');
assert.equal(entries[0].row.shift,'B조');assert.equal(entries[0].recordIndex,0);assert.equal(entries[1].recordIndex,1);
assert.equal(handoverEntries({...saved,work_report:{records:[],legacy_memo:''}},equipment).length,0);
assert.equal(handoverEntries(saved,equipment)[0].row.occurred,'미기재','never substitute the shift start for occurrence time');
assert.throws(()=>selectedReportPayload({...draft,records:[{...draft.records[0],occurred_at:'not-a-date'}]},equipment),/발생시각/);
const legacy = handoverTableRow({shift_date:'2026-10-15',author_name:'이전 담당자',open_items:[{text:'HPU-01 재확인',status:'open'}]},equipment);
assert.equal(legacy.date,'2026-10-15');assert.equal(legacy.hours,'미기재');
assert.equal(legacy.equipment,'HPU-01');assert.match(legacy.summary,/재확인/);assert.match(legacy.results,/조치 필요/);
const missing = handoverTableRow({kind:'work_log',equipment_ids:['UNKNOWN']},equipment);
assert.equal(missing.author,'미기재');assert.equal(missing.equipment,'UNKNOWN');assert.equal(missing.date,'미기재');
const zoned = handoverTableRow({...saved,required_context:{author:'검증',start_at:'2026-10-15T23:00:00Z',end_at:'2026-10-16T07:00:00Z'}},equipment);
assert.equal(zoned.date,'2026-10-16');assert.equal(zoned.hours,'08:00 – 16:00');
const unsafe = handoverTableRow({...saved,memo_text:'<img src=x onerror=alert(1)>',work_report:{records:[]}},equipment);
assert.equal(unsafe.summary,'<img src=x onerror=alert(1)>','render the original text without interpreting HTML');
console.log('PASS: work-log columns, multiple records/equipment, overnight hours, timezone, legacy/missing data, immutable source');
